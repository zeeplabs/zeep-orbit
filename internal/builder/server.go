// The builder HTTP API is called only by Orbit, server to server, but it runs
// on behalf of an LLM that may have been prompt-injected, so the server is
// written as if every byte after the token check were hostile:
//
//   - every route needs X-Builder-Token, verified against the session id taken
//     from the ROUTE (never from the token), the method and the request path;
//   - every error is one JSON envelope {"error":{"code","message"}}. Tool-level
//     failures (the LLM must read "old_string not found") carry their safe
//     English message; infrastructure failures (i/o, git, panics) are logged
//     server side and answered with a fixed generic message;
//   - every route caps its request body (http.MaxBytesReader) and has its own
//     context timeout and read/write deadlines, so a slow client cannot pin a
//     goroutine or a per-session lock;
//   - preview files are generated by untrusted code: they are opened relative
//     to the session root with os.Root (no escape), never through a symlink,
//     and every preview response carries a CSP sandbox header;
//   - logs hold method, route pattern, session id, status and duration only,
//     never tokens, bodies, query strings or file contents.
//
// Health signing convention (for the Orbit client): GET /v1/health has no
// session, so the token is minted with the literal session id "-"
// (HealthSessionID): SignRequest("-", "GET", "/v1/health").

const (
	// TokenHeader is the request header that carries the Orbit -> builder
	// request token (see [Signer.SignRequest]).
	TokenHeader = "X-Builder-Token"

	// HealthSessionID is the session id Orbit must use when signing the token
	// of GET /v1/health, which has no session in its route.
	HealthSessionID = "-"

	// DefaultMaxActiveSessions is used when ServerConfig.MaxActiveSessions is
	// not positive.
	DefaultMaxActiveSessions = 4

	// DefaultTemplateName is the template served for ?template=default.
	DefaultTemplateName = "default"

	templateVersionFile = "TEMPLATE_VERSION"

	// previewCSP puts every preview response in an opaque origin even when the
	// URL is opened top-level (design section 10). No allow-same-origin.
	previewCSP = "sandbox allow-scripts allow-forms allow-popups allow-modals"

	retryAfterSeconds = "5"

	maxTemplateNameLen = 64
	maxVersionFileLen  = 64
	maxPreviewPathLen  = 1024
	maxPreviewSegment  = 255

	// Request body caps. The JSON caps are deliberately generous relative to
	// the workspace limits (a 512 KiB file may grow several times once JSON
	// escaped) but small enough to bound memory per request.
	maxOpsBody    = 2 << 20
	maxSmallBody  = 64 << 10
	maxNoBodySize = 1 << 10

	// Per-route time budgets (context timeout; the connection deadlines add a
	// small margin). Build is the longest: install 5m plus the npm install
	// fallback is already bounded inside the Executor, this is the outer
	// safety net.
	opsTimeout     = 30 * time.Second
	initTimeout    = 3 * time.Minute
	restoreTimeout = 4 * time.Minute
	commitTimeout  = 2 * time.Minute
	buildTimeout   = 12 * time.Minute
	archiveTimeout = 2 * time.Minute
	previewTimeout = 2 * time.Minute
	smallTimeout   = 15 * time.Second
	deadlineMargin = 10 * time.Second
)

var templateNamePattern = regexp.MustCompile(`^[a-z0-9-]+$`)

// ---- wire types (shared with the Orbit client) ----

// ErrorBody is the payload of every error response.
type ErrorBody struct {
	// Code is a stable snake_case identifier clients switch on.
	Code string `json:"code"`
	// Message is a short English description. It never holds host paths or
	// raw internal errors for 5xx responses.
	Message string `json:"message"`
}

// ErrorResponse is the uniform error envelope.
type ErrorResponse struct {
	// Error describes the failure.
	Error ErrorBody `json:"error"`
}

// InitResponse is the result of POST /v1/sessions/{id}/init.
type InitResponse struct {
	// SHA is the "turn 0" commit.
	SHA string `json:"sha"`
	// Bundle is the full git bundle of HEAD, base64 (standard alphabet).
	Bundle string `json:"bundle"`
	// TemplateVersion is the content of the template's TEMPLATE_VERSION file,
	// or "" when absent.
	TemplateVersion string `json:"template_version"`
}

// RestoreBundle is one snapshot passed to restore, in apply order.
type RestoreBundle struct {
	// Seq is the turn the bundle belongs to (informational).
	Seq int `json:"seq"`
	// SHA is the commit the bundle must yield; verified when set.
	SHA string `json:"sha"`
	// Data is the git bundle, base64 on the wire.
	Data []byte `json:"data"`
}

// RestoreRequest is the body of POST /v1/sessions/{id}/restore.
type RestoreRequest struct {
	// Bundles are ordered: a full bundle first, then incremental ones.
	Bundles []RestoreBundle `json:"bundles"`
}

// RestoreResponse is the result of restore.
type RestoreResponse struct {
	// SHA is the restored HEAD.
	SHA string `json:"sha"`
}

// OpsArgs are the tool arguments of one file operation. Only the fields that
// belong to the operation kind are used.
type OpsArgs struct {
	Path       string `json:"path"`
	Offset     int    `json:"offset"`
	Limit      int    `json:"limit"`
	Content    string `json:"content"`
	OldString  string `json:"old_string"`
	NewString  string `json:"new_string"`
	ReplaceAll bool   `json:"replace_all"`
}

// OpsRequest is the body of POST /v1/sessions/{id}/ops.
type OpsRequest struct {
	// OpID is the idempotency key (required for write_file and edit_file).
	OpID string `json:"op_id"`
	// Kind is list_dir, read_file, write_file or edit_file.
	Kind string `json:"kind"`
	// Args holds the operation arguments.
	Args OpsArgs `json:"args"`
}

// OpsResponse is the result of an operation.
type OpsResponse struct {
	// OK is true for every successful operation.
	OK bool `json:"ok"`
	// Output is the text returned to the model.
	Output string `json:"output"`
	// Replayed is true when the stored result of op_id was returned.
	Replayed bool `json:"replayed"`
}

// BuildRequest is the body of POST /v1/sessions/{id}/build.
type BuildRequest struct {
	// OpID is the idempotency key.
	OpID string `json:"op_id"`
	// Step is install, typecheck, lint or build.
	Step string `json:"step"`
	// PreviewBase is the vite --base value; only used by the build step.
	PreviewBase string `json:"preview_base"`
}

// BuildResponse is the result of a build step. A non-zero ExitCode is a normal
// 200 response.
type BuildResponse struct {
	ExitCode   int    `json:"exit_code"`
	OutputTail string `json:"output_tail"`
	DurationMs int64  `json:"duration_ms"`
	TimedOut   bool   `json:"timed_out"`
	Replayed   bool   `json:"replayed"`
}

// BuildLogResponse is the result of GET /v1/sessions/{id}/build-log.
type BuildLogResponse struct {
	// Output is the tail of the last output of the step.
	Output string `json:"output"`
}

// CommitRequest is the body of POST /v1/sessions/{id}/commit.
type CommitRequest struct {
	// TurnSeq is the turn the commit belongs to.
	TurnSeq int `json:"turn_seq"`
	// Message is an optional commit subject suffix (sanitized by git.go).
	Message string `json:"message"`
}

// CommitResponse is the result of commit and revert.
type CommitResponse struct {
	// SHA is the commit now at HEAD.
	SHA string `json:"sha"`
	// Prev is the previous HEAD.
	Prev string `json:"prev"`
	// Changed is false when nothing changed and no commit was created.
	Changed bool `json:"changed"`
	// Bundle is the incremental bundle Prev..SHA, base64; "" when unchanged.
	Bundle string `json:"bundle"`
}

// RevertRequest is the body of POST /v1/sessions/{id}/revert.
type RevertRequest struct {
	// ToSHA is a full 40-hex ancestor of HEAD.
	ToSHA string `json:"to_sha"`
	// TurnSeq is the turn the revert commit belongs to.
	TurnSeq int `json:"turn_seq"`
}

// HealthResponse is the result of GET /v1/health.
type HealthResponse struct {
	// Active is the number of sessions with a request in flight.
	Active int `json:"active"`
	// Capacity is BUILDER_MAX_ACTIVE_SESSIONS.
	Capacity int `json:"capacity"`
	// Version is the builder build version.
	Version string `json:"version"`
	// DefaultTemplateVersion is the TEMPLATE_VERSION of the default template.
	DefaultTemplateVersion string `json:"default_template_version"`
}

// ---- configuration ----

// ServerConfig wires a [Server] to the builder components.
type ServerConfig struct {
	// WorkDir holds one directory per session (BUILDER_WORK_DIR). Required,
	// absolute and existing.
	WorkDir string
	// TemplatesDir holds one directory per template (BUILDER_TEMPLATES_DIR).
	// Empty disables ?template=.
	TemplatesDir string
	// Signer verifies X-Builder-Token. Required.
	Signer *Signer
	// Registry hands out one Workspace per session. When nil a registry with
	// default limits is created. When set it must be rooted at WorkDir.
	Registry *WorkspaceRegistry
	// Executor runs build steps. Required.
	Executor *Executor
	// Git runs the snapshot operations. Required.
	Git *GitRepo
	// MaxActiveSessions is the capacity limit (default 4).
	MaxActiveSessions int
	// Version is reported by health (default "dev").
	Version string
	// Logger receives one line per request (default slog.Default()).
	Logger *slog.Logger
}

// Server is the builder HTTP API.
//
// Serve Handler with an http.Server whose WriteTimeout is nonzero and at
// least as long as the longest route (build, 12 minutes plus margin): the
// server resets the write deadline at the start of every request, and the
// per-route deadlines set here only tighten it.
type Server struct {
	workDir      string
	templatesDir string
	signer       *Signer
	registry     *WorkspaceRegistry
	exec         *Executor
	git          *GitRepo
	capacity     int
	version      string
	log          *slog.Logger

	active     *activeTracker
	initCap    int64
	restoreCap int64

	handler http.Handler
}

// NewServer validates cfg and builds the server.
func NewServer(cfg ServerConfig) (*Server, error) {
	if cfg.Signer == nil || cfg.Executor == nil || cfg.Git == nil {
		return nil, fmt.Errorf("signer, executor and git are required: %w", ErrInvalidArgument)
	}
	if cfg.WorkDir == "" || !filepath.IsAbs(cfg.WorkDir) {
		return nil, fmt.Errorf("work dir must be an absolute path: %w", ErrInvalidArgument)
	}
	workDir := filepath.Clean(cfg.WorkDir)
	if fi, err := os.Stat(workDir); err != nil || !fi.IsDir() {
		return nil, fmt.Errorf("work dir must be an existing directory: %w", ErrInvalidArgument)
	}
	reg := cfg.Registry
	if reg == nil {
		reg = NewWorkspaceRegistry(workDir, WorkspaceLimits{})
	} else if filepath.Clean(reg.workDir) != workDir {
		return nil, fmt.Errorf("registry work dir differs from the server work dir: %w", ErrInvalidArgument)
	}
	capacity := cfg.MaxActiveSessions
	if capacity <= 0 {
		capacity = DefaultMaxActiveSessions
	}
	version := cfg.Version
	if version == "" {
		version = "dev"
	}
	logger := cfg.Logger
	if logger == nil {
		logger = slog.Default()
	}
	tl := cfg.Git.cfg.Tar
	s := &Server{
		workDir:      workDir,
		templatesDir: cfg.TemplatesDir,
		signer:       cfg.Signer,
		registry:     reg,
		exec:         cfg.Executor,
		git:          cfg.Git,
		capacity:     capacity,
		version:      version,
		log:          logger,
		active:       &activeTracker{capacity: capacity, counts: make(map[string]int)},
		// Init cap: all file bytes plus a tar header and padding (up to 1 KiB)
		// per entry plus slack; Init itself enforces the exact limits.
		initCap: tl.MaxTotalBytes + int64(tl.MaxFiles)*1024 + 1<<20,
		// Restore cap: base64 of the total bundle budget plus JSON overhead.
		restoreCap: base64Len(cfg.Git.cfg.MaxRestoreBytes) + 2<<20,
	}
	s.handler = s.routes()
	return s, nil
}

// Handler returns the http.Handler serving the whole API.
func (s *Server) Handler() http.Handler { return s.handler }

func base64Len(n int64) int64 { return (n + 2) / 3 * 4 }

// ---- routing ----

type trackMode int

const (
	trackNone   trackMode = iota // not counted as active
	trackAdmit                   // counted, and refused at capacity when the session is idle
	trackAlways                  // counted, never refused
)

type routeOpts struct {
	fixedID        string // session id used for the token when the route has none
	maxBody        int64
	timeout        time.Duration
	track          trackMode
	requireSession bool // 404 unknown_session before doing anything else
	previewHeaders bool
}

// call carries per-request facts the handlers need.
type call struct {
	id string
	// sole is true when this request is the only one in flight for the
	// session, which makes it safe to clean up a stale half-created session.
	sole bool
}

type handlerFunc func(w http.ResponseWriter, r *http.Request, c *call)

func (s *Server) routes() http.Handler {
	mux := http.NewServeMux()
	const sess = "/v1/sessions/{id}"
	mux.Handle("GET /v1/health", s.route(routeOpts{fixedID: HealthSessionID, maxBody: maxNoBodySize, timeout: smallTimeout}, s.handleHealth))
	mux.Handle("POST "+sess+"/init", s.route(routeOpts{maxBody: s.initCap, timeout: initTimeout, track: trackAdmit}, s.handleInit))
	mux.Handle("POST "+sess+"/restore", s.route(routeOpts{maxBody: s.restoreCap, timeout: restoreTimeout, track: trackAdmit}, s.handleRestore))
	mux.Handle("POST "+sess+"/ops", s.route(routeOpts{maxBody: maxOpsBody, timeout: opsTimeout, track: trackAdmit, requireSession: true}, s.handleOps))
	mux.Handle("POST "+sess+"/build", s.route(routeOpts{maxBody: maxSmallBody, timeout: buildTimeout, track: trackAdmit, requireSession: true}, s.handleBuild))
	mux.Handle("GET "+sess+"/build-log", s.route(routeOpts{maxBody: maxNoBodySize, timeout: smallTimeout, requireSession: true}, s.handleBuildLog))
	mux.Handle("POST "+sess+"/commit", s.route(routeOpts{maxBody: maxSmallBody, timeout: commitTimeout, track: trackAlways, requireSession: true}, s.handleCommit))
	mux.Handle("POST "+sess+"/revert", s.route(routeOpts{maxBody: maxSmallBody, timeout: commitTimeout, track: trackAlways, requireSession: true}, s.handleRevert))
	mux.Handle("GET "+sess+"/archive", s.route(routeOpts{maxBody: maxNoBodySize, timeout: archiveTimeout, requireSession: true}, s.handleArchive))
	previewOpts := routeOpts{maxBody: maxNoBodySize, timeout: previewTimeout, requireSession: true, previewHeaders: true}
	mux.Handle("GET "+sess+"/preview", s.route(previewOpts, s.handlePreview))
	mux.Handle("GET "+sess+"/preview/{path...}", s.route(previewOpts, s.handlePreview))
	mux.Handle("DELETE "+sess, s.route(routeOpts{maxBody: maxNoBodySize, timeout: smallTimeout}, s.handleDelete))
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		writeError(w, http.StatusNotFound, "not_found", "no such route")
	})
	return s.middleware(mux)
}

// route wraps a handler with, in this order: preview headers, token check,
// session id validation, session existence, body cap and deadlines, and
// capacity tracking. Authentication comes before everything that touches the
// filesystem or reads the body, so an unauthenticated caller learns nothing.
func (s *Server) route(o routeOpts, h handlerFunc) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if o.previewHeaders {
			setPreviewHeaders(w.Header())
		}
		id := o.fixedID
		if id == "" {
			id = r.PathValue("id")
		}
		if err := s.signer.VerifyRequest(r.Header.Get(TokenHeader), id, r.Method, r.URL.Path); err != nil {
			writeError(w, http.StatusUnauthorized, "unauthorized", "missing or invalid builder token")
			return
		}
		if o.fixedID == "" {
			if _, err := SessionRoot(s.workDir, id); err != nil {
				s.fail(w, r, id, err)
				return
			}
			if o.requireSession && !s.sessionExists(id) {
				s.fail(w, r, id, ErrSessionNotFound)
				return
			}
		}

		ctx, cancel := context.WithTimeout(r.Context(), o.timeout)
		defer cancel()
		r = r.WithContext(ctx)
		r.Body = http.MaxBytesReader(w, r.Body, o.maxBody)
		// Body reads have no server-wide timeout (ReadTimeout is 0 so large
		// uploads are not cut by a global value): bound them per route.
		rc := http.NewResponseController(w)
		deadline := time.Now().Add(o.timeout + deadlineMargin)
		_ = rc.SetReadDeadline(deadline)  // ErrNotSupported on recorders is fine
		_ = rc.SetWriteDeadline(deadline) // tightens the server's WriteTimeout

		c := &call{id: id}
		if o.track != trackNone {
			release, n, ok := s.active.acquire(id, o.track == trackAdmit)
			if !ok {
				w.Header().Set("Retry-After", retryAfterSeconds)
				writeError(w, http.StatusTooManyRequests, "at_capacity", "builder is at capacity, retry later")
				return
			}
			defer release()
			c.sole = n == 1
		}
		h(w, r, c)
	})
}

func setPreviewHeaders(h http.Header) {
	h.Set("Content-Security-Policy", previewCSP)
	h.Set("X-Content-Type-Options", "nosniff")
	h.Set("Cache-Control", "no-store")
	h.Set("Referrer-Policy", "no-referrer")
	// No X-Frame-Options: Orbit's preview proxy sets SAMEORIGIN.
}

// ---- middleware ----

// statusWriter records the status for the request log. Unwrap keeps
// http.ResponseController (deadlines, flush) working.
type statusWriter struct {
	http.ResponseWriter
	status int
	wrote  bool
}

func (w *statusWriter) WriteHeader(code int) {
	if !w.wrote {
		w.status = code
		w.wrote = true
	}
	w.ResponseWriter.WriteHeader(code)
}

func (w *statusWriter) Write(p []byte) (int, error) {
	if !w.wrote {
		w.status = http.StatusOK
		w.wrote = true
	}
	return w.ResponseWriter.Write(p)
}

// Unwrap exposes the underlying writer to http.ResponseController.
func (w *statusWriter) Unwrap() http.ResponseWriter { return w.ResponseWriter }

// middleware rejects non-canonical paths, recovers from panics and writes the
// one-line request log. It must not clone the request: r.Pattern and the path
// values are filled in by the mux on this same *http.Request.
func (s *Server) middleware(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		start := time.Now()
		sw := &statusWriter{ResponseWriter: w, status: http.StatusOK}
		defer func() {
			rec := recover()
			if rec != nil && rec != http.ErrAbortHandler {
				s.log.Error("builder handler panic", "panic", fmt.Sprint(rec), "stack", string(debug.Stack()))
				if !sw.wrote {
					writeError(sw, http.StatusInternalServerError, "internal_error", "internal error")
				}
			}
			pattern := r.Pattern
			if pattern == "" {
				pattern = "(unmatched)"
			}
			s.log.LogAttrs(r.Context(), slog.LevelInfo, "builder request",
				slog.String("method", r.Method),
				slog.String("route", pattern),
				slog.String("session", r.PathValue("id")),
				slog.Int("status", sw.status),
				slog.Duration("duration", time.Since(start)),
			)
			if rec == http.ErrAbortHandler {
				panic(rec) // let net/http drop the connection after a torn stream
			}
		}()
		// Decoded path: "%2e%2e" and "%2f" tricks show up here as ".." and "/".
		if hasUncleanPath(r.URL.Path) {
			writeError(sw, http.StatusBadRequest, "invalid_path", "request path is not canonical")
			return
		}
		next.ServeHTTP(sw, r)
	})
}

// hasUncleanPath reports a path with "." or ".." segments, empty segments
// (other than a trailing slash), NUL bytes or backslashes.
func hasUncleanPath(p string) bool {
	if p == "" || p[0] != '/' || strings.ContainsAny(p, "\x00\\") {
		return true
	}
	segs := strings.Split(p[1:], "/")
	for i, seg := range segs {
		if seg == "." || seg == ".." || (seg == "" && i != len(segs)-1) {
			return true
		}
	}
	return false
}

// ---- capacity ----

// activeTracker counts in-flight requests per session. A session is "active"
// while its count is positive.
type activeTracker struct {
	mu       sync.Mutex
	capacity int
	counts   map[string]int
}

// acquire registers one request for id. With enforce set, a request for an
// idle session is refused when capacity sessions are already active; requests
// for an already active session are always admitted. n is the number of
// in-flight requests for id after registration.
func (t *activeTracker) acquire(id string, enforce bool) (release func(), n int, ok bool) {
	t.mu.Lock()
	defer t.mu.Unlock()
	if enforce && t.counts[id] == 0 && len(t.counts) >= t.capacity {
		return nil, 0, false
	}
	t.counts[id]++
	n = t.counts[id]
	var once sync.Once
	return func() {
		once.Do(func() {
			t.mu.Lock()
			defer t.mu.Unlock()
			if t.counts[id]--; t.counts[id] <= 0 {
				delete(t.counts, id)
			}
		})
	}, n, true
}

func (t *activeTracker) count() int {
	t.mu.Lock()
	defer t.mu.Unlock()
	return len(t.counts)
}

// ---- errors ----

// apiError is an error with an explicit HTTP mapping, for failures that come
// from the server layer itself rather than from workspace/exec/git.
type apiError struct {
	status int
	code   string
	msg    string
}

func (e *apiError) Error() string { return e.msg }

func badRequest(code, msg string) error { return &apiError{http.StatusBadRequest, code, msg} }

// mapError converts an error from the builder packages (or this file) into an
// HTTP status, a stable snake_case code and a client-safe English message.
// Tool-level failures (4xx) carry the error's own message, which the packages
// guarantee is free of host paths. Everything else is answered with a fixed
// generic message: the caller logs the real error.
func mapError(err error) (status int, code, msg string) {
	var ae *apiError
	if errors.As(err, &ae) {
		return ae.status, ae.code, ae.msg
	}
	var mbe *http.MaxBytesError
	if errors.As(err, &mbe) {
		return http.StatusRequestEntityTooLarge, "body_too_large", "request body is too large"
	}
	switch {
	case errors.Is(err, context.DeadlineExceeded):
		return http.StatusGatewayTimeout, "timeout", "the operation timed out"
	case errors.Is(err, ErrGitTimeout):
		return http.StatusGatewayTimeout, "timeout", "the operation timed out"
	case errors.Is(err, context.Canceled):
		return http.StatusServiceUnavailable, "canceled", "the request was canceled"
	}

	type rule struct {
		target error
		status int
		code   string
	}
	rules := []rule{
		{ErrInvalidSessionID, http.StatusBadRequest, "invalid_session_id"},
		{ErrSessionNotFound, http.StatusNotFound, "unknown_session"},
		{ErrNoRepo, http.StatusNotFound, "unknown_session"},
		{ErrNotFound, http.StatusNotFound, "not_found"},

		{ErrPathOutside, http.StatusForbidden, "path_outside"},
		{ErrPathForbidden, http.StatusForbidden, "path_forbidden"},
		{ErrSymlink, http.StatusForbidden, "symlink_forbidden"},

		{ErrFileTooLarge, http.StatusRequestEntityTooLarge, "file_too_large"},
		{ErrSessionTooLarge, http.StatusRequestEntityTooLarge, "session_too_large"},
		{ErrArchiveTooLarge, http.StatusRequestEntityTooLarge, "archive_too_large"},
		{ErrBundleTooLarge, http.StatusRequestEntityTooLarge, "bundle_too_large"},

		{ErrOpIDReused, http.StatusConflict, "op_id_reused"},
		{ErrRepoExists, http.StatusConflict, "session_exists"},
		{ErrRootNotEmpty, http.StatusConflict, "session_exists"},

		{ErrInvalidPath, http.StatusUnprocessableEntity, "invalid_path"},
		{ErrInvalidArgument, http.StatusUnprocessableEntity, "invalid_argument"},
		{ErrUnknownOp, http.StatusUnprocessableEntity, "unknown_op"},
		{ErrEditEmptyOld, http.StatusUnprocessableEntity, "edit_empty_old"},
		{ErrEditNoop, http.StatusUnprocessableEntity, "edit_noop"},
		{ErrEditNotFound, http.StatusUnprocessableEntity, "edit_not_found"},
		{ErrEditNotUnique, http.StatusUnprocessableEntity, "edit_not_unique"},
		{ErrInvalidContent, http.StatusUnprocessableEntity, "invalid_content"},
		{ErrBinaryFile, http.StatusUnprocessableEntity, "binary_file"},
		{ErrIsDirectory, http.StatusUnprocessableEntity, "is_directory"},
		{ErrNotDirectory, http.StatusUnprocessableEntity, "not_directory"},
		{ErrNotRegular, http.StatusUnprocessableEntity, "not_regular"},
		{ErrUnknownStep, http.StatusUnprocessableEntity, "unknown_step"},
		{ErrInvalidPreviewBase, http.StatusUnprocessableEntity, "invalid_preview_base"},
		{ErrInvalidSHA, http.StatusUnprocessableEntity, "invalid_sha"},
		{ErrUnknownCommit, http.StatusUnprocessableEntity, "unknown_commit"},
		{ErrNotAncestor, http.StatusUnprocessableEntity, "not_ancestor"},
		{ErrInvalidArchive, http.StatusUnprocessableEntity, "invalid_archive"},
		{ErrUnsafeArchiveEntry, http.StatusUnprocessableEntity, "unsafe_archive_entry"},
		{ErrBundleVerify, http.StatusUnprocessableEntity, "bundle_verify_failed"},
		{ErrUnsafeContent, http.StatusUnprocessableEntity, "unsafe_content"},
	}
	for _, r := range rules {
		if errors.Is(err, r.target) {
			return r.status, r.code, err.Error()
		}
	}
	// ErrIO, ErrOpLog, ErrGitFailed, ErrGitUnavailable, ErrExecStart and
	// anything unknown: never expose the details.
	return http.StatusInternalServerError, "internal_error", "internal error"
}

// causeOf returns the host-level cause of an OpError/GitError, for logs only.
func causeOf(err error) error {
	var c interface{ Cause() error }
	if errors.As(err, &c) {
		return c.Cause()
	}
	return nil
}

// fail writes the mapped error response, logging the real error for 5xx.
func (s *Server) fail(w http.ResponseWriter, r *http.Request, sessionID string, err error) {
	status, code, msg := mapError(err)
	if status >= 500 {
		s.log.Error("builder request failed",
			"route", r.Pattern, "session", sessionID, "code", code,
			"error", err, "cause", causeOf(err))
	}
	writeError(w, status, code, msg)
}

func writeError(w http.ResponseWriter, status int, code, msg string) {
	writeJSON(w, status, ErrorResponse{Error: ErrorBody{Code: code, Message: msg}})
}

func writeJSON(w http.ResponseWriter, status int, v any) {
	h := w.Header()
	h.Set("Content-Type", "application/json")
	h.Set("Cache-Control", "no-store")
	h.Set("X-Content-Type-Options", "nosniff")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v) // a failed write means the client is gone
}

// decodeJSON reads one JSON object from the (already size-capped) body. It
// writes the error response itself and reports whether decoding succeeded.
func (s *Server) decodeJSON(w http.ResponseWriter, r *http.Request, c *call, dst any) bool {
	dec := json.NewDecoder(r.Body)
	dec.DisallowUnknownFields()
	err := dec.Decode(dst)
	if err == nil {
		// Exactly one value: trailing garbage is a malformed request.
		if _, terr := dec.Token(); !errors.Is(terr, io.EOF) {
			err = errors.New("trailing data")
		}
	}
	if err == nil {
		return true
	}
	var mbe *http.MaxBytesError
	if errors.As(err, &mbe) {
		s.fail(w, r, c.id, err)
		return false
	}
	// Parser detail is not echoed: it may quote attacker-controlled bytes.
	writeError(w, http.StatusBadRequest, "invalid_json", "request body is not valid JSON for this route")
	return false
}

// ---- session lifecycle helpers ----

func (s *Server) root(id string) (string, error) { return SessionRoot(s.workDir, id) }

// sessionExists reports whether the session directory exists as a real
// directory. A session "exists" exactly when its directory does.
func (s *Server) sessionExists(id string) bool {
	root, err := s.root(id)
	if err != nil {
		return false
	}
	li, err := os.Lstat(root)
	return err == nil && li.IsDir() && li.Mode()&fs.ModeSymlink == 0
}

// createSession makes the empty session directory for init/restore. It fails
// with a session_exists error when the directory is already there. A leftover
// directory without a repository (a crash between mkdir and the first commit)
// is removed first, but only when this request is the sole one for the
// session, so a concurrent init is never wiped.
func (s *Server) createSession(c *call) (string, error) {
	root, err := s.root(c.id)
	if err != nil {
		return "", err
	}
	s.registry.Forget(c.id)
	err = os.Mkdir(root, 0o700)
	if errors.Is(err, fs.ErrExist) && c.sole && isStaleSession(root) {
		if rerr := os.RemoveAll(root); rerr != nil {
			return "", &OpError{Err: ErrIO, cause: rerr}
		}
		err = os.Mkdir(root, 0o700)
	}
	switch {
	case err == nil:
		return root, nil
	case errors.Is(err, fs.ErrExist):
		return "", &GitError{Err: ErrRepoExists}
	default:
		return "", &OpError{Err: ErrIO, cause: err}
	}
}

func isStaleSession(root string) bool {
	li, err := os.Lstat(root)
	if err != nil || !li.IsDir() || li.Mode()&fs.ModeSymlink != 0 {
		return false
	}
	_, err = os.Lstat(filepath.Join(root, gitDirName))
	return errors.Is(err, fs.ErrNotExist)
}

// removeSession deletes a session directory after checking that it is a
// direct child of the work dir. root always comes from [SessionRoot], so this
// is defense in depth against a future caller passing something else.
func (s *Server) removeSession(id, root string) error {
	if filepath.Dir(root) != s.workDir {
		return &OpError{Err: ErrIO, cause: fmt.Errorf("refusing to remove %q: not a session directory", filepath.Base(root))}
	}
	s.registry.Forget(id)
	if err := os.RemoveAll(root); err != nil {
		return &OpError{Err: ErrIO, cause: err}
	}
	return nil
}

