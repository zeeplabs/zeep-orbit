// lazyStream delays the 200 and the tar headers until the first byte, so an
// error that happens before any output (bad sha, no repo) still gets a proper
// JSON error response.
type lazyStream struct {
	w       http.ResponseWriter
	started bool
}

func (l *lazyStream) Write(p []byte) (int, error) {
	if !l.started {
		l.started = true
		h := l.w.Header()
		h.Set("Content-Type", "application/x-tar")
		h.Set("Cache-Control", "no-store")
		h.Set("X-Content-Type-Options", "nosniff")
		l.w.WriteHeader(http.StatusOK)
	}
	return l.w.Write(p)
}

func (s *Server) handleArchive(w http.ResponseWriter, r *http.Request, c *call) {
	sha := r.URL.Query().Get("sha")
	if sha == "" {
		sha = "HEAD"
	}
	root, err := s.root(c.id)
	if err != nil {
		s.fail(w, r, c.id, err)
		return
	}
	// Archive holds the per-session git lock while it writes, so a client that
	// stops reading would block commits. The route's write deadline (set in
	// route) bounds that; the context timeout kills git itself.
	ls := &lazyStream{w: w}
	if err := s.git.Archive(r.Context(), root, sha, ls); err != nil {
		if !ls.started {
			s.fail(w, r, c.id, err)
			return
		}
		// Headers are gone: a clean-looking short tar would be silently
		// corrupt. Abort the connection so the client sees a failed transfer.
		s.log.Error("archive stream failed", "session", c.id, "error", err, "cause", causeOf(err))
		panic(http.ErrAbortHandler)
	}
	if !ls.started { // git produced no output at all: still a valid empty response
		_, _ = ls.Write(nil)
	}
}

func (s *Server) handleDelete(w http.ResponseWriter, r *http.Request, c *call) {
	root, err := s.root(c.id)
	if err != nil {
		s.fail(w, r, c.id, err)
		return
	}
	li, err := os.Lstat(root)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		s.registry.Forget(c.id)
		w.WriteHeader(http.StatusNoContent)
		return
	case err != nil:
		s.fail(w, r, c.id, &OpError{Err: ErrIO, cause: err})
		return
	}
	// Wait for a running build step of this session (it holds the same lock),
	// otherwise npm would keep writing into a directory being removed.
	if li.IsDir() && li.Mode()&fs.ModeSymlink == 0 {
		if real, rerr := filepath.EvalSymlinks(root); rerr == nil {
			unlock, lerr := s.exec.sessionLocks.acquire(r.Context(), real)
			if lerr != nil {
				s.fail(w, r, c.id, lerr)
				return
			}
			defer unlock()
		}
	}
	if err := s.removeSession(c.id, root); err != nil {
		s.fail(w, r, c.id, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

// ---- preview ----

// splitPreviewPath turns the wildcard value into path segments. The mux has
// already unescaped it, so "..%2f" arrives here as "../": every segment is
// validated again instead of trusting the earlier path check.
func splitPreviewPath(raw string) ([]string, bool) {
	if raw == "" {
		return nil, true
	}
	if len(raw) > maxPreviewPathLen || strings.ContainsAny(raw, "\x00\\") {
		return nil, false
	}
	segs := strings.Split(raw, "/")
	if segs[len(segs)-1] == "" { // trailing slash: a directory request
		segs = segs[:len(segs)-1]
	}
	for _, seg := range segs {
		if seg == "" || seg == "." || seg == ".." || len(seg) > maxPreviewSegment {
			return nil, false
		}
		for _, r := range seg {
			if r < 0x20 || r == 0x7f {
				return nil, false
			}
		}
	}
	return segs, true
}

// previewRel is the preview directory relative to the session root.
var previewRel = orbitDirName + "/" + previewDirName

func (s *Server) handlePreview(w http.ResponseWriter, r *http.Request, c *call) {
	segs, ok := splitPreviewPath(r.PathValue("path"))
	if !ok {
		writeError(w, http.StatusBadRequest, "invalid_path", "invalid preview path")
		return
	}
	root, err := s.root(c.id)
	if err != nil {
		s.fail(w, r, c.id, err)
		return
	}
	// os.Root makes escaping the session root impossible even through
	// symlinks planted by build tools; the explicit Lstat walk below also
	// refuses to serve through a symlink at all.
	rt, err := os.OpenRoot(root)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			s.fail(w, r, c.id, ErrSessionNotFound)
			return
		}
		s.fail(w, r, c.id, &OpError{Err: ErrIO, cause: err})
		return
	}
	defer rt.Close()

	if !isPlainDir(rt, orbitDirName) || !isPlainDir(rt, previewRel) {
		writeError(w, http.StatusNotFound, "no_preview", "no successful build yet")
		return
	}

	// 1. the requested file (or its index.html when it names a directory)
	if len(segs) > 0 {
		if f, fi, ok := openPreviewFile(rt, segs); ok {
			serveFile(w, r, f, fi)
			return
		}
		if li, ok := lstatPreview(rt, segs); ok && li.IsDir() {
			if f, fi, ok := openPreviewFile(rt, append(append([]string(nil), segs...), "index.html")); ok {
				serveFile(w, r, f, fi)
				return
			}
		}
	}
	// 2. SPA fallback: client-side routes have no file extension, and a
	// browser navigation (Accept: text/html) must get the app shell too.
	// A missing asset (a script or image request) stays a 404 so a broken
	// reference is not masked by HTML.
	isRoot := len(segs) == 0
	hasExt := !isRoot && filepath.Ext(segs[len(segs)-1]) != ""
	wantsHTML := strings.Contains(r.Header.Get("Accept"), "text/html")
	if isRoot || !hasExt || wantsHTML {
		if f, fi, ok := openPreviewFile(rt, []string{"index.html"}); ok {
			serveFile(w, r, f, fi)
			return
		}
	}
	writeError(w, http.StatusNotFound, "not_found", "no such file in the preview")
}

func isPlainDir(rt *os.Root, name string) bool {
	li, err := rt.Lstat(name)
	return err == nil && li.IsDir() && li.Mode()&fs.ModeSymlink == 0
}

// lstatPreview Lstats segs under the preview directory component by
// component and fails when any component is missing or a symlink.
func lstatPreview(rt *os.Root, segs []string) (fs.FileInfo, bool) {
	cur := previewRel
	var li fs.FileInfo
	for i, seg := range segs {
		cur += "/" + seg
		var err error
		li, err = rt.Lstat(cur)
		if err != nil || li.Mode()&fs.ModeSymlink != 0 {
			return nil, false
		}
		if i < len(segs)-1 && !li.IsDir() {
			return nil, false
		}
	}
	return li, li != nil
}

// openPreviewFile opens a regular file under the preview directory without
// following symlinks (O_NOFOLLOW on the last component, Lstat on the others).
func openPreviewFile(rt *os.Root, segs []string) (*os.File, fs.FileInfo, bool) {
	li, ok := lstatPreview(rt, segs)
	if !ok || !li.Mode().IsRegular() {
		return nil, nil, false
	}
	f, err := rt.OpenFile(previewRel+"/"+strings.Join(segs, "/"), os.O_RDONLY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		return nil, nil, false
	}
	fi, err := f.Stat()
	if err != nil || !fi.Mode().IsRegular() {
		_ = f.Close()
		return nil, nil, false
	}
	return f, fi, true
}

func serveFile(w http.ResponseWriter, r *http.Request, f *os.File, fi fs.FileInfo) {
	defer f.Close()
	// ServeContent picks the type from the extension, handles Range and HEAD.
	http.ServeContent(w, r, fi.Name(), fi.ModTime(), f)
}
